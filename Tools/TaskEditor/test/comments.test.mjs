import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
test('comments render Markdown, page long threads, and guests cannot post',()=>{
 const dom=new JSDOM(readFileSync(new URL('../src/index.html',import.meta.url),'utf8'),{url:'file:///TaskEditor/index.html',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window,messages=[];w.TextEncoder=TextEncoder;w.webkit={messageHandlers:{taskEditor:{postMessage:m=>messages.push(m)}}};
 w.eval(readFileSync(new URL('../../../Sources/ContinuumRevived/Resources/TaskEditor/editor.js',import.meta.url),'utf8'));
 const comments=Array.from({length:51},(_,i)=>({id:String(i),authorID:'local',authorName:'You',createdAt:'2026-11-02T12:00:00Z',body:'**Update '+i+'**'}));
 const state={title:'Task',body:'Description',attachments:[],agents:[],columns:[],comments};w.taskEditor.load(state);
 assert.equal(w.document.querySelectorAll('.comment').length,11);
 w.document.getElementById('comment-pages').firstChild.click();assert.equal(w.document.querySelectorAll('.comment').length,20);
 assert.ok(w.document.querySelector('.comment strong'));
 w.document.getElementById('comment-body').value='Hello';w.document.getElementById('post-comment').click();assert.equal(messages.at(-1).type,'addComment');
 w.taskEditor.commentSaved('addComment');
 w.document.getElementById('comment-body').value='    indented code\n';w.document.getElementById('post-comment').click();
 assert.equal(messages.at(-1).body,'    indented code\n','comment composition preserves Markdown indentation');
 w.taskEditor.commentSaved('addComment');
 const first=w.document.querySelector('.comment');
 first.querySelector('.comment-edit').click();w.document.getElementById('comment-body').value='Edited';w.document.getElementById('post-comment').click();
 assert.equal(messages.at(-1).type,'editComment');assert.match(messages.at(-1).expectedBody,/\*\*Update/,'edit carries the baseline body for conflict protection');
 w.taskEditor.commentSaved('editComment');
 assert.equal(w.document.getElementById('post-comment').disabled,false);
 w.taskEditor.load({...state,readOnly:true});
 assert.equal(w.document.getElementById('comment-compose').hidden,true);
 assert.equal(w.document.querySelectorAll('.comment-edit').length,0);
 const before=messages.length;w.document.getElementById('post-comment').click();assert.equal(messages.length,before);
 w.taskEditor.load({...state,comments:Array.from({length:10000},(_,i)=>({...comments[0],id:'large-'+i}))});
 assert.equal(w.document.querySelectorAll('#comments .tiptap').length,20,'ten thousand comments keep only one page of renderers');
 assert.match(w.document.getElementById('comment-pages').textContent,/10000 comments/,'all withheld pages remain discoverable');
 dom.window.taskEditor?.dispose?.();dom.window.close();
});
